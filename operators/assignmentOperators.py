
# 4. Assignment Operators

x = 10

print("Assignment")
print(x)

x += 5
print("Add Assignment")
print(x)

x -= 3
print("Subtract Assignment")
print(x)

x *= 2
print("Multiply Assignment")
print(x)

x /= 4
print("Divide Assignment")
print(x)

x //= 2
print("Floor Divide Assignment")
print(x)

x %= 3
print("Modulus Assignment")
print(x)

x **= 2
print("Exponent Assignment")
print(x)


